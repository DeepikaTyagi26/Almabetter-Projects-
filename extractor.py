# Send to OpenAI wrapper (returns raw text)
resp_text = analyze_with_openai(prompt_text=prompt, as_json=False, max_tokens=1200)

# Try parse JSON
parsed = safe_parse_json(resp_text)
if not parsed:
    # As fallback, ask the model for a concise summary and simple extraction
    fallback_prompt = f"Summarize this resume in 2 sentences and list top 8 skills. Resume text:\n{filepath}"
    fallback = analyze_with_openai(prompt_text=fallback_prompt, as_json=False, max_tokens=400)
    parsed = {
        "name": None,
        "email": None,
        "phone": None,
        "location": None,
        "summary": fallback,
        "skills": [],
        "experience": [],
        "education": [],
        "certifications": [],
        "confidence": 0.4
    }

# Ensure keys exist and types
for k in SCHEMA_KEYS:
    if k not in parsed:
        parsed[k] = None if k not in ("skills","experience","education","certifications") else []

# Normalize confidence
try:
    confidence = float(parsed.get("confidence") or 0.0)
    confidence = min(max(confidence, 0.0), 1.0)
except Exception:
    confidence = 0.0

# When content fields are raw strings, ensure lists are lists
if isinstance(parsed.get("skills"), str):
    parsed["skills"] = [s.strip() for s in re.split(r"[,;\\n]+", parsed["skills"]) if s.strip()]

return parsed, parsed.get("summary",""), confidence
