UPLOAD_DIR = "uploaded_docs"
os.makedirs(UPLOAD_DIR, exist_ok=True)

def save_uploaded_file(uploaded_file):
    """Save uploaded file to uploaded_docs and return path."""
    try:
        ext = uploaded_file.name.split(".")[-1]
        name = f"{uuid.uuid4()}.{ext}"
        path = os.path.join(UPLOAD_DIR, name)
        with open(path, "wb") as f:
            f.write(uploaded_file.getbuffer())
        return path
    except Exception as e:
        return None

def extract_text_from_pdf(path_or_bytes):
    """Extract text from a PDF file or bytes-like stream."""
    try:
        if isinstance(path_or_bytes, (bytes, bytearray)):
            fp = io.BytesIO(path_or_bytes)
            with pdfplumber.open(fp) as pdf:
                return "\n".join([p.extract_text() or "" for p in pdf.pages])
        else:
            with pdfplumber.open(path_or_bytes) as pdf:
                return "\n".join([p.extract_text() or "" for p in pdf.pages])
    except Exception as e:
        return f"[ERROR] PDF extraction failed: {e}"

def extract_text_from_docx(path_or_bytes):
    try:
        if isinstance(path_or_bytes, (bytes, bytearray)):
            f = io.BytesIO(path_or_bytes)
            doc = docx.Document(f)
        else:
            doc = docx.Document(path_or_bytes)
        return "\n".join([p.text for p in doc.paragraphs])
    except Exception as e:
        return f"[ERROR] DOCX extraction failed: {e}"

def extract_text_from_txt(path_or_bytes):
    try:
        if isinstance(path_or_bytes, (bytes, bytearray)):
            return path_or_bytes.decode("utf-8", errors="ignore")
        with open(path_or_bytes, "r", encoding="utf-8", errors="ignore") as f:
            return f.read()
    except Exception as e:
        return f"[ERROR] TXT extraction failed: {e}"

def extract_text_from_image(path_or_bytes):
    try:
        if isinstance(path_or_bytes, (bytes, bytearray)):
            img = Image.open(io.BytesIO(path_or_bytes))
        else:
            img = Image.open(path_or_bytes)
        return pytesseract.image_to_string(img)
    except Exception as e:
        return f"[ERROR] IMAGE OCR failed: {e}"

def extract_document(path):
    """Auto-detect file type by extension and extract text."""
    ext = Path(path).suffix.lower()
    if ext == ".pdf":
        return extract_text_from_pdf(path)
    if ext == ".docx":
        return extract_text_from_docx(path)
    if ext == ".txt":
        return extract_text_from_txt(path)
    if ext in [".png", ".jpg", ".jpeg", ".tiff", ".bmp"]:
        return extract_text_from_image(path)
    return "[ERROR] Unsupported file type."

# ---------------------------
# OpenAI wrapper (2.x compatible)
# ---------------------------
def analyze_with_openai(document_text: str, user_prompt: str, model: str = "gpt-4o-mini", max_tokens: int = 800):
    """
    Sends a prompt to OpenAI and returns the assistant content.
    """
    if not document_text:
        return "[ERROR] No document text provided."
    system_msg = "You are a precise assistant that extracts structured resume information and summarizes key skills, experience, and education."
    user_msg = f"{user_prompt}\n\nDocument:\n{document_text}"
    try:
        response = openai.chat.completions.create(
            model=model,
            messages=[
                {"role": "system", "content": system_msg},
                {"role": "user", "content": user_msg}
            ],
            max_tokens=max_tokens,
            temperature=0.0
        )
        # v2.x returns ChatCompletionMessage objects
        return response.choices[0].message.content
    except Exception as e:
        return f"[ERROR] OpenAI call failed: {e}"

