# Step 1: Upload
st.header("1) Upload Resume")
uploaded_file = st.file_uploader("Upload PDF, DOCX, TXT or Image (PNG/JPG)", type=["pdf","docx","txt","png","jpg","jpeg"])

if uploaded_file:
    saved_path = save_uploaded_file(uploaded_file)
    if not saved_path:
        st.error("Failed to save uploaded file.")
        st.stop()

    st.success(f"Saved to {saved_path}")
    with st.spinner("Extracting text..."):
        extracted_text = extract_document(saved_path)
    st.subheader("Extracted Text (preview)")
    st.text_area("Document text", extracted_text[:20000], height=240)

    # Step 2: AI Analysis
    st.header("2) AI Analysis")
    default_prompt = "Extract structured resume fields: name, email, phone, location, summary (1-2 sentences), skills (list), experience (list of {title, company, start_date, end_date, description}), education (list), certifications (list). Return as concise JSON object and then a short human summary."
    user_prompt = st.text_input("Analysis prompt", value=default_prompt)
    analyze_btn = st.button("Run AI Analysis", key="analyze_button")

    if analyze_btn:
        with st.spinner("Calling OpenAI..."):
            ai_output = analyze_with_openai(extracted_text, user_prompt)
        st.session_state["ai_output_raw"] = ai_output
        st.success("AI analysis complete")
        st.subheader("AI Raw Output")
        st.code(ai_output)

        # Try to parse JSON if model returned JSON first
        parsed_json = None
        try:
            # attempt to find a JSON substring from ai_output
            text = ai_output.strip()
            # if text starts with { assume json
            if text.startswith("{") or text.startswith("["):
                parsed_json = json.loads(text)
            else:
                # try to extract {...}
                start = text.find("{")
                end = text.rfind("}")
                if start != -1 and end != -1 and end > start:
                    candidate = text[start:end+1]
                    parsed_json = json.loads(candidate)
        except Exception:
            parsed_json = None

        st.subheader("Parsed JSON (if any)")
        if parsed_json:
            st.json(parsed_json)
            st.session_state["ai_output_json"] = parsed_json
        else:
            st.info("AI did not return JSON or parsing failed. You can edit the raw output or proceed with raw text.")

    # Step 3: Send to n8n
    st.header("3) Send to n8n Email Workflow")
    webhook_url = st.text_input("n8n Webhook URL", value=DEFAULT_N8N)
    recipient_override = st.text_input("Recipient email (optional)", value="")
    note = st.text_area("Optional note to include in the email", value="")

    send_btn = st.button("Send to n8n", key="send_n8n_button")

    if send_btn:
        # Ensure we have AI output to send (prefer parsed JSON but fall back to raw)
        ai_analysis_text = st.session_state.get("ai_output_raw", "")
        ai_analysis_json = st.session_state.get("ai_output_json", None)

        payload = {
            "filename": uploaded_file.name,
            "resume_data": extracted_text,
            "analysis": ai_analysis_text,
            "analysis_json": ai_analysis_json,
            "note": note
        }
        if recipient_override:
            payload["email"] = recipient_override

        if not webhook_url:
            st.error("Please provide a valid n8n webhook URL.")
        else:
            try:
                with st.spinner("Sending to n8n..."):
                    r = requests.post(webhook_url, json=payload, timeout=20)
                    r.raise_for_status()
                st.success("Data successfully sent to n8n.")
                st.markdown("✅ Check your email (or n8n executions) for the message.")
            except requests.exceptions.HTTPError as he:
                st.error(f"n8n responded with HTTP error: {he} - {he.response.text if he.response is not None else ''}")
            except Exception as e:
                st.error(f"Failed to send to n8n: {e}")

